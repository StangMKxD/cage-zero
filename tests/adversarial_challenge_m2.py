        print("\n=== Challenge 7: Cryptographic & Working Tree Integrity ===")
        # Check source FBX hashes for all 15 clips
        fbx_failures = 0
        for fbx_name, expected_hash in KNOWN_SOURCE_HASHES.items():
            fbx_path = SOURCE_DIR / fbx_name
            if not fbx_path.is_file():
                self.log("C7_Integrity", f"{fbx_name}_exists", False, f"Missing: {fbx_path}")
                fbx_failures += 1
                continue
            actual_hash = compute_sha256(fbx_path)
            matches = (actual_hash == expected_hash)
            if not matches:
                fbx_failures += 1
            self.log(
                "C7_Integrity",
                f"{fbx_name}_sha256_unmodified",
                matches,
                f"Hash={actual_hash} vs Expected={expected_hash}"
            )

