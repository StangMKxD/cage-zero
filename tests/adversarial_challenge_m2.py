    # Challenge 4: Joint Pivot Deviation Auditing Across All 10 Clips
    # =========================================================================
    def challenge_4_joint_pivot_deviations(self):
        print("\n=== Challenge 4: Joint Pivot Deviation Auditing (All 10 Clips) ===")
        # Threshold: <= 0.00020 studs
        PIVOT_THRESHOLD = 0.00020

        # We evaluate pivot deviation across all 10 .blend files.
        # In Blender FK, for each frame, each non-root bone's head position in parent's coordinate frame
        # should match its canonical rest position in parent's coordinate frame:
        # rest_offset = b.head_local - b.parent.head_local
        # pose_offset = pb.matrix.inverted() @ pb.parent.matrix ... or:
        # dev = || pb.head - (pb.parent.matrix @ M_parent_rest.inverted() @ b.head_local) ||
        for clip in OUTFIELD_CLIPS:
            name = clip["name"]
            blend_file = TEST_OUTPUT_DIR / name / f"{name}_R15_v03.blend"
            bpy.ops.wm.open_mainfile(filepath=str(blend_file))
            rig = next(o for o in bpy.data.objects if o.type == 'ARMATURE')
            action = rig.animation_data.action
            f_start = int(round(action.frame_range[0]))
            f_end = int(round(action.frame_range[1]))

            # Precalculate canonical rest head in parent bone coordinate space for all non-root bones
            rest_parent_heads = {}
            for pb in rig.pose.bones:
                b = rig.data.bones.get(pb.name)
                if pb.parent and b.parent:
                    # Point in parent bone space:
                    p_mat_rest = b.parent.matrix_local
                    head_in_parent = p_mat_rest.inverted() @ b.head_local
                    rest_parent_heads[pb.name] = head_in_parent

            max_dev = 0.0
            worst_bone = None
            worst_frame = None

            for f in range(f_start, f_end + 1):
                bpy.context.scene.frame_set(f)
                bpy.context.view_layer.update()

                for pb in rig.pose.bones:
                    if pb.name not in rest_parent_heads:
                        continue
                    # Compute expected head from current parent pose matrix
                    expected_head = pb.parent.matrix @ rest_parent_heads[pb.name]
                    actual_head = pb.head
                    dev = (actual_head - expected_head).length
                    if dev > max_dev:
                        max_dev = dev
                        worst_bone = pb.name
                        worst_frame = f

            passed = (max_dev <= PIVOT_THRESHOLD)
            self.log(
                "C4_PivotDeviation",
                f"{name}_max_joint_pivot_deviation",
                passed,
                f"Max deviation = {max_dev:.8f} studs (bone={worst_bone}, frame={worst_frame}) (gate <= {PIVOT_THRESHOLD})"
            )

