    # Challenge 2: Deep Stress-Testing of StandingIdle02
    # =========================================================================
    def challenge_2_standing_idle_deep_stress(self):
        print("\n=== Challenge 2: Deep Stress-Testing StandingIdle02 ===")
        blend_file = TEST_OUTPUT_DIR / "StandingIdle02" / "StandingIdle02_R15_v03.blend"
        bpy.ops.wm.open_mainfile(filepath=str(blend_file))
        rig = None
