            # Compute L1 norm between first and last frame poses
            diff = 0.0
            for p1, p2 in zip(f_first, f_last):
                for v1, v2 in zip(p1, p2):
                    diff += abs(v1 - v2)

            if is_loop:
                # Loops MUST have seam closed (diff ~ 0.0)
                self.log(
                    "C5_SeamBranching",
                    f"{name}_loop_seam_closed",
                    diff < 1e-4,
                    f"Loop first vs last frame L1 diff = {diff:.8f} (expected < 1e-4)"
                )
            else:
                # One-shots MUST NOT have seam closed (diff > 0.50)
                self.log(
                    "C5_SeamBranching",
                    f"{name}_oneshot_recovery_preserved",
                    diff > 0.50,
                    f"One-shot first vs recovery frame L1 diff = {diff:.4f} (expected > 0.50)"
                )

