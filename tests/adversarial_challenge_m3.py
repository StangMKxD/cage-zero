def compute_sha256(filepath: Path) -> str:
    hasher = hashlib.sha256()
    with open(filepath, 'rb') as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest().upper()


def get_all_fcurves(action) -> list[Any]:
    legacy = getattr(action, "fcurves", None)
    if legacy is not None and len(legacy) > 0:
        return list(legacy)
    curves = []
    for layer in getattr(action, "layers", ()):
        for strip in getattr(layer, "strips", ()):
            for channelbag in getattr(strip, "channelbags", ()):
                curves.extend(channelbag.fcurves)
    return curves


def compute_bone_front_dot(rig: bpy.types.Object, bone_name: str) -> float:
    pb = rig.pose.bones.get(bone_name)
    b = rig.data.bones.get(bone_name)
    if not pb or not b:
        return 0.0
    pb_z = pb.matrix.to_3x3() @ Vector((0, 0, 1))
    ref_z = b.matrix_local.to_3x3() @ Vector((0, 0, 1))
    if pb_z.length < 1e-6 or ref_z.length < 1e-6:
        return 0.0
    return float(pb_z.normalized().dot(ref_z.normalized()))


