    # Challenge 1: Non-Root Bone Translation Leakage Auditing
    # =========================================================================
    def challenge_1_non_root_translation_leakage(self):
        print("\n=== Challenge 1: Non-Root Bone Translation Leakage Auditing ===")
        for clip in GOALKEEPER_CLIPS:
            name = clip["name"]
            slug = clip["slug"]
            blend_file = TEST_OUTPUT_DIR / name / f"{name}_R15_v03.blend"

            if not blend_file.is_file():
                self.log("C1_NonRootTranslation", f"{name}_blend_exists", False, f"Missing: {blend_file}")
                continue

            bpy.ops.wm.open_mainfile(filepath=str(blend_file))
            rig = next((o for o in bpy.data.objects if o.type == 'ARMATURE'), None)
            if not rig or not rig.animation_data or not rig.animation_data.action:
                self.log("C1_NonRootTranslation", f"{name}_rig_action_exists", False, "Missing armature or action")
                continue

            action = rig.animation_data.action
            curves = get_all_fcurves(action)

            # 1.1 Check F-curves in .blend: NO non-root location curves
            non_root_curves = [
                c for c in curves
                if 'location' in c.data_path and 'LowerTorso' not in c.data_path and 'HumanoidRootPart' not in c.data_path
            ]
            self.log(
                "C1_NonRootTranslation",
                f"{name}_blend_non_root_fcurves_zero",
                len(non_root_curves) == 0,
                f"Found {len(non_root_curves)} non-root location F-curves in .blend (strictly expected 0)"
            )

            # 1.2 Check LowerTorso location curves presence in .blend
            lt_loc_curves = [c for c in curves if 'location' in c.data_path and 'LowerTorso' in c.data_path]
            self.log(
                "C1_NonRootTranslation",
                f"{name}_blend_lowertorso_location_curves_present",
                len(lt_loc_curves) == 3,
                f"LowerTorso location curves in .blend = {len(lt_loc_curves)} (expected 3)"
            )

            # 1.3 Check Pose Bone Memory across all frames: pb.location must be strictly 0.00000000
            f_start = int(round(action.frame_range[0]))
            f_end = int(round(action.frame_range[1]))
            max_non_root_pose_loc = 0.0
            worst_pose_bone = None
            worst_pose_frame = None

            for f in range(f_start, f_end + 1):
                bpy.context.scene.frame_set(f)
                bpy.context.view_layer.update()
                for pb in rig.pose.bones:
                    if pb.name == 'LowerTorso':
                        continue
                    loc_len = pb.location.length
                    if loc_len > max_non_root_pose_loc:
                        max_non_root_pose_loc = loc_len
                        worst_pose_bone = pb.name
                        worst_pose_frame = f

            self.log(
                "C1_NonRootTranslation",
                f"{name}_pose_memory_non_root_strictly_zero",
                max_non_root_pose_loc == 0.0,
                f"Max non-root pose bone translation = {max_non_root_pose_loc:.8f} studs (bone={worst_pose_bone}, frame={worst_pose_frame})"
            )

            # 1.4 Check Keyframes JSON: all 14 child bones pose[:3] strictly 0.00000000
            kf_names = [f"{name}-r15-keyframes.json", f"{slug}-r15-keyframes.json"]
            for kf_file_name in kf_names:
                kf_path = TEST_OUTPUT_DIR / name / kf_file_name
                if not kf_path.is_file():
                    self.log("C1_NonRootTranslation", f"{name}_{kf_file_name}_exists", False, f"Missing: {kf_path}")
                    continue
                with open(kf_path, "r", encoding="utf-8") as f:
                    kf_data = json.load(f)

                non_root_leaks = 0
                max_leak_mag = 0.0
                for f_entry in kf_data.get('frames', []):
                    for j_idx, j_name in enumerate(ORDER):
                        if j_name == 'LowerTorso':
                            continue
                        pos = f_entry['poses'][j_idx][:3]
                        mag = math.sqrt(sum(v * v for v in pos))
                        if mag > max_leak_mag:
                            max_leak_mag = mag
                        if any(abs(v) > 1e-7 for v in pos):
                            non_root_leaks += 1

                self.log(
                    "C1_NonRootTranslation",
                    f"{name}_{kf_file_name}_non_root_strictly_zero",
                    non_root_leaks == 0,
                    f"Violations={non_root_leaks}, max_mag={max_leak_mag:.8f} studs (threshold 0.00000000)"
                )

            # 1.5 Check Recipe JSON: all non-root tracks have key position == [0.0, 0.0, 0.0]
            rc_path = TEST_OUTPUT_DIR / name / f"{name}.recipe.json"
            if not rc_path.is_file():
                self.log("C1_NonRootTranslation", f"{name}_recipe_exists", False, f"Missing: {rc_path}")
                continue
            with open(rc_path, "r", encoding="utf-8") as f:
                rc_data = json.load(f)

            rc_non_root_leaks = 0
            max_rc_leak = 0.0
            for track in rc_data.get('tracks', []):
                if track.get('joint') == 'LowerTorso':
                    continue
                for key in track.get('keys', []):
                    pos = key.get('position', [0.0, 0.0, 0.0])
                    mag = math.sqrt(sum(v * v for v in pos))
                    if mag > max_rc_leak:
                        max_rc_leak = mag
                    if any(abs(v) > 1e-7 for v in pos):
                        rc_non_root_leaks += 1

            self.log(
                "C1_NonRootTranslation",
                f"{name}_recipe_json_non_root_strictly_zero",
                rc_non_root_leaks == 0,
                f"Violations={rc_non_root_leaks}, max_pos={max_rc_leak:.8f} studs"
            )

    # =========================================================================
    # Challenge 2: Joint Pivot Deviation Auditing
    # =========================================================================
    def challenge_2_joint_pivot_deviation(self):
        print("\n=== Challenge 2: Joint Pivot Deviation Auditing across All Frames ===")
        PIVOT_TOLERANCE = 0.00020  # studs

        for clip in GOALKEEPER_CLIPS:
            name = clip["name"]
            blend_file = TEST_OUTPUT_DIR / name / f"{name}_R15_v03.blend"
            bpy.ops.wm.open_mainfile(filepath=str(blend_file))
            rig = next(o for o in bpy.data.objects if o.type == 'ARMATURE')
            action = rig.animation_data.action
            f_start = int(round(action.frame_range[0]))
            f_end = int(round(action.frame_range[1]))

            # Precalculate canonical rest head offset in parent rest matrix for 14 child bones
            # LowerTorso is the root bone that translates, so only 14 non-root child bones are audited
            rest_parent_heads = {}
            for pb in rig.pose.bones:
                if pb.name == 'LowerTorso':
                    continue
                b = rig.data.bones.get(pb.name)
                if pb.parent and b.parent:
                    p_mat_rest = b.parent.matrix_local
                    head_in_parent = p_mat_rest.inverted() @ b.head_local
                    rest_parent_heads[pb.name] = head_in_parent

            max_pivot_dev = 0.0
            worst_bone = None
            worst_frame = None

            for f in range(f_start, f_end + 1):
                bpy.context.scene.frame_set(f)
                bpy.context.view_layer.update()

                for pb in rig.pose.bones:
                    if pb.name not in rest_parent_heads:
                        continue
                    expected_head = pb.parent.matrix @ rest_parent_heads[pb.name]
                    dev = (pb.head - expected_head).length
                    if dev > max_pivot_dev:
                        max_pivot_dev = dev
                        worst_bone = pb.name
                        worst_frame = f

            passed = (max_pivot_dev <= PIVOT_TOLERANCE)
            self.log(
                "C2_PivotDeviation",
                f"{name}_joint_pivot_deviation",
                passed,
                f"Max deviation = {max_pivot_dev:.8e} studs (bone={worst_bone}, frame={worst_frame}) (gate <= {PIVOT_TOLERANCE})"
            )

            # Cross check with audit JSON
            audit_file = TEST_OUTPUT_DIR / name / f"{name}_audit.json"
            if audit_file.is_file():
                with open(audit_file, "r", encoding="utf-8") as f:
                    audit_data = json.load(f)
                reported_dev = audit_data.get("max_pivot_deviation", 0.0)
                diff = abs(max_pivot_dev - reported_dev)
                self.log(
                    "C2_PivotDeviation",
                    f"{name}_audit_json_pivot_consistency",
                    diff < 1e-6,
                    f"Measured={max_pivot_dev:.8e} vs AuditJSON={reported_dev:.8e} (diff={diff:.2e})"
                )

    # =========================================================================
    # Challenge 3: Knee Flexion, Front Dot Positivity & Patella Stress-Testing
    # =========================================================================
    def challenge_3_knee_flexion_and_patella_stress(self):
        print("\n=== Challenge 3: Knee Flexion, Front Dot Positivity & Patella Stress-Testing ===")
        for clip in GOALKEEPER_CLIPS:
            name = clip["name"]
            expected_min_dot = clip["min_dot"]
            blend_file = TEST_OUTPUT_DIR / name / f"{name}_R15_v03.blend"
            bpy.ops.wm.open_mainfile(filepath=str(blend_file))
            rig = next(o for o in bpy.data.objects if o.type == 'ARMATURE')
            action = rig.animation_data.action
            f_start = int(round(action.frame_range[0]))
            f_end = int(round(action.frame_range[1]))

            left_lower_dots = []
            right_lower_dots = []
            left_euler_x = []
            right_euler_x = []

            for f in range(f_start, f_end + 1):
                bpy.context.scene.frame_set(f)
                bpy.context.view_layer.update()

                ll_dot = compute_bone_front_dot(rig, 'LeftLowerLeg')
                rl_dot = compute_bone_front_dot(rig, 'RightLowerLeg')
                left_lower_dots.append(ll_dot)
                right_lower_dots.append(rl_dot)

                # Bone local rotation in Euler degrees (X is knee flexion hinge)
                pb_ll = rig.pose.bones['LeftLowerLeg']
                pb_rl = rig.pose.bones['RightLowerLeg']
                e_l = pb_ll.rotation_quaternion.to_euler()
                e_r = pb_rl.rotation_quaternion.to_euler()
                left_euler_x.append(math.degrees(e_l.x))
                right_euler_x.append(math.degrees(e_r.x))

            peak_left = max(left_lower_dots)
            peak_right = max(right_lower_dots)
            min_left = min(left_lower_dots)
            min_right = min(right_lower_dots)
            f1_left = left_lower_dots[0]
            f1_right = right_lower_dots[0]

            # 3.1 Peak knee front dot >= +0.70
            self.log(
                "C3_KneeFrontDot",
                f"{name}_peak_knee_front_dot",
                peak_left >= expected_min_dot and peak_right >= expected_min_dot,
                f"Peak Left={peak_left:.4f}, Right={peak_right:.4f} (gate >= {expected_min_dot})"
            )

            # 3.2 Frame 1 alignment forward (> 0.0)
            self.log(
                "C3_KneeFrontDot",
                f"{name}_frame1_knee_alignment",
                f1_left > 0.0 and f1_right > 0.0,
                f"Frame 1 Left={f1_left:.4f}, Right={f1_right:.4f} (both > 0.0)"
            )

            # 3.3 Patella anti-inversion check: knees must never point inverted backward (min dot > -0.50)
            self.log(
                "C3_KneeFrontDot",
                f"{name}_anti_inversion_patella_check",
                min_left > -0.50 and min_right > -0.50,
                f"Min dot Left={min_left:.4f}, Right={min_right:.4f} (no inverted backward patella > -0.50)"
            )

            # 3.4 Natural backward knee flexion check:
            # When the leg flexes deeply, Euler X rotation is negative (bending shin backward, not hyperextending forward)
            deep_flex_l = [x for x in left_euler_x if x < -20.0]
            deep_flex_r = [x for x in right_euler_x if x < -20.0]
            hyperext_l = [x for x in left_euler_x if x > 20.0]
            hyperext_r = [x for x in right_euler_x if x > 20.0]

            natural_flexion = (len(deep_flex_l) > 0 or len(deep_flex_r) > 0) and len(hyperext_l) == 0 and len(hyperext_r) == 0
            self.log(
                "C3_KneeFrontDot",
                f"{name}_natural_knee_flexion_direction",
                natural_flexion,
                f"Left min Euler X={min(left_euler_x):.1f}°, Right min Euler X={min(right_euler_x):.1f}° (hyperextensions > +20°: L={len(hyperext_l)}, R={len(hyperext_r)})"
            )

