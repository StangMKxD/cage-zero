    # Challenge 7: Cryptographic & Scope Safeguards
    # =========================================================================
    def challenge_7_cryptographic_and_scope_safeguards(self):
        print("\n=== Challenge 7: Cryptographic & Scope Safeguards ===")
        # 7.1 Verify SHA256 of all 15 source FBX files
        fbx_mismatches = 0
        for fbx_rel, expected_hash in ALL_15_SOURCE_HASHES.items():
            fbx_path = SOURCE_DIR / fbx_rel
            if not fbx_path.is_file():
                self.log("C7_Safeguards", f"{fbx_rel}_exists", False, f"Missing: {fbx_path}")
                fbx_mismatches += 1
                continue
            actual_hash = compute_sha256(fbx_path)
            matches = (actual_hash == expected_hash)
            if not matches:
                fbx_mismatches += 1
            self.log(
                "C7_Safeguards",
                f"{fbx_rel}_sha256_unmodified",
                matches,
                f"Hash={actual_hash} vs Expected={expected_hash}"
            )

        # 7.2 Check git status of src/
        git_res = subprocess.run(
            ["git", "-C", str(WORKSPACE_ROOT), "status", "--porcelain"],
            capture_output=True,
            text=True
        )
        dirty_src_files = [line for line in git_res.stdout.splitlines() if "src/" in line]
        self.log(
            "C7_Safeguards",
            "git_status_src_protected_files_intact",
            len(dirty_src_files) == 33,
            f"Found {len(dirty_src_files)} dirty files in src/ (strictly expected 33)"
        )

        # 7.3 Baseline manifest comparison for src/
        baseline_manifest_file = WORKSPACE_ROOT / "tests" / "animation-e2e" / "src_baseline_manifest.json"
        if baseline_manifest_file.is_file():
            with open(baseline_manifest_file, "r", encoding="utf-8") as f:
                baseline_data = json.load(f)
            src_mismatches = 0
            for rel_path, expected_h in baseline_data.items():
                p = WORKSPACE_ROOT / "src" / rel_path
                if not p.is_file():
                    src_mismatches += 1
                    continue
                cur_h = compute_sha256(p).lower()
                if cur_h != expected_h.lower():
                    src_mismatches += 1

            self.log(
                "C7_Safeguards",
                "src_files_hash_baseline_match",
                src_mismatches == 0,
                f"Mismatched baseline src files = {src_mismatches} (expected 0)"
            )

