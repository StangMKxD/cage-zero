    # Challenge 5: Seam Closure vs One-Shot Recovery Preservation
    # =========================================================================
    def challenge_5_seam_and_recovery_branching(self):
        print("\n=== Challenge 5: Seam Closure vs One-Shot Recovery Branching ===")
        for clip in GOALKEEPER_CLIPS:
            name = clip["name"]
            is_loop = clip["loop"]
            kf_path = TEST_OUTPUT_DIR / name / f"{name}-r15-keyframes.json"

            with open(kf_path, "r", encoding="utf-8") as f:
                kf_data = json.load(f)

            frames = kf_data['frames']
            f_first = frames[0]['poses']
            f_last = frames[-1]['poses']

            # Compute L1 norm between first and last frame poses
            diff = 0.0
            for p1, p2 in zip(f_first, f_last):
                for v1, v2 in zip(p1, p2):
                    diff += abs(v1 - v2)

            if is_loop:
                self.log(
                    "C5_SeamBranching",
                    f"{name}_loop_seam_closed",
                    diff < 1e-4,
                    f"Loop first vs last frame L1 diff = {diff:.8f} (expected < 1e-4)"
                )
            else:
                self.log(
                    "C5_SeamBranching",
                    f"{name}_oneshot_recovery_preserved",
                    diff > 0.50,
                    f"One-shot first vs recovery frame L1 diff = {diff:.4f} (expected > 0.50)"
                )

